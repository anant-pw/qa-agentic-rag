"""
Hand-written holdout eval for /generate/agentic (NEXT_STEPS_PLAN.md Step 4).

Why a separate set from eval/eval_seed.json: the frozen 20 are generated by
generate_eval_seed.py from the same reference graph and regexes the system
uses, and every gold document is one of the original 28. This set is
written by hand against the 173-doc corpus: paraphrases, near-duplicate
synthetic documents, multi-hop, unanswerable and false-premise questions.
Expected facts in eval/holdout.json were read from Postgres, not assumed.

Grading is deliberately mechanical (substring checks, case-insensitive,
dash-normalised) so two models are graded identically:
  must_include_all  every string must appear
  must_include_any  at least one must appear
  min_of            at least n of the listed ids must appear
  must_not_include  none may appear
  expect=abstain           answer must read as "not in the documents"
  expect=reject_or_abstain a guardrail reject also passes
A FAIL is a signal to read the answer, not a final verdict -- the summary
prints every FAIL so it can be hand-checked.

The route (semantic / field_lookup / ...) and timings are read from the
matching logs/generation.jsonl line, so run against a live stack whose
./logs is mounted (docker-compose.yml) and with no other traffic.

Run:
    python -m eval.run_holdout --label qwen3-4b-instruct
    python -m eval.run_holdout --label phi4-14b --only-semantic-from eval/runs/<qwen run>/holdout_results.json
"""

import argparse
import json
import os
import time

import httpx

BASE_URL = os.environ.get("EVAL_BASE_URL", "http://127.0.0.1:8000")
LOG_PATH = os.path.join("logs", "generation.jsonl")
TIMEOUT = float(os.environ.get("EVAL_REQUEST_TIMEOUT", "6000"))

ABSTAIN_PHRASES = [
    "not specified", "not mention", "no mention", "does not mention", "doesn't mention",
    "not include", "does not include", "doesn't include", "not available", "not stated",
    "does not state", "doesn't state", "not recorded", "no record", "no information",
    "not provided", "not present", "not found", "not in the corpus", "cannot be determined",
    "can't be determined", "cannot determine", "not contain", "does not contain",
    "doesn't contain", "no details", "not documented", "unknown", "do not state",
    "do not mention", "do not include", "do not provide", "does not provide",
    "doesn't provide", "not given", "there is no", "do not address", "does not address",
    "doesn't address",
]
REJECT_PHRASES = ["doesn't appear to be about", "does not appear to be about", "no answer was generated"]
_DASHES = dict.fromkeys(map(ord, "‐‑‒–—―−"), "-")


def _norm(text: str) -> str:
    return (text or "").translate(_DASHES).replace("’", "'").lower()


def grade(item: dict, answer: str) -> list[str]:
    a = _norm(answer)
    problems = []
    for s in item.get("must_include_all", []):
        if _norm(s) not in a:
            problems.append(f"missing {s!r}")
    anys = item.get("must_include_any")
    if anys and not any(_norm(s) in a for s in anys):
        problems.append(f"none of {anys!r}")
    if "min_of" in item:
        ids, n = item["min_of"]["ids"], item["min_of"]["n"]
        hit = [i for i in ids if _norm(i) in a]
        if len(hit) < n:
            problems.append(f"only {len(hit)}/{n} of {ids} ({hit})")
    for s in item.get("must_not_include", []):
        if _norm(s) in a:
            problems.append(f"contains forbidden {s!r}")
    expect = item.get("expect")
    if expect in ("abstain", "reject_or_abstain"):
        abstained = any(p in a for p in ABSTAIN_PHRASES)
        rejected = any(p in a for p in REJECT_PHRASES)
        if not (abstained or (expect == "reject_or_abstain" and rejected)):
            problems.append("did not abstain")
    return problems


def _last_log_for(question: str) -> dict:
    try:
        with open(LOG_PATH, encoding="utf-8") as f:
            lines = f.readlines()[-20:]
    except OSError:
        return {}
    for line in reversed(lines):
        try:
            rec = json.loads(line)
        except json.JSONDecodeError:
            continue
        if rec.get("question") == question:
            return rec
    return {}


def run(label: str, holdout_path: str, out_dir: str, only_ids: set[str] | list[str] | None):
    with open(holdout_path, encoding="utf-8") as f:
        items = json.load(f)
    if only_ids is not None:
        by_id = {i["id"]: i for i in items}
        items = ([by_id[i] for i in only_ids if i in by_id] if isinstance(only_ids, list)
                 else [i for i in items if i["id"] in only_ids])
    os.makedirs(out_dir, exist_ok=True)

    results = []
    for n, item in enumerate(items, 1):
        payload = {"question": item["question"], "no_cache": True, **item.get("filters", {})}
        t0 = time.perf_counter()
        try:
            resp = httpx.post(f"{BASE_URL}/generate/agentic", json=payload, timeout=TIMEOUT)
            resp.raise_for_status()
            text = resp.text
            error = None
        except httpx.HTTPError as e:
            text, error = "", f"{type(e).__name__}: {e}"
        wall = time.perf_counter() - t0
        answer, _, sources_block = text.partition("---SOURCES---")
        try:
            sources = [s["external_id"] for s in json.loads(sources_block.strip())] if sources_block.strip() else []
        except (json.JSONDecodeError, KeyError, TypeError):
            sources = []
        log = _last_log_for(item["question"])
        route = (log.get("retrieval") or {}).get("path")
        gen = log.get("generation") or {}
        problems = ["request error: " + error] if error else grade(item, answer)
        result = "ERROR" if error else ("PASS" if not problems else "FAIL")
        results.append({
            "id": item["id"], "category": item["category"], "question": item["question"],
            "filters": item.get("filters", {}), "result": result, "problems": problems,
            "route": route, "wall_s": round(wall, 1),
            "first_token_s": gen.get("first_token_s"), "output_tokens": gen.get("ollama_output_tokens"),
            "context_ids": (log.get("retrieval") or {}).get("doc_ids"),
            "answer": answer.strip(), "sources": sources, "truth": item.get("truth"),
        })
        print(f"[{n}/{len(items)}] {item['id']} {result:5} route={route} {wall:6.1f}s"
              + (f"  {problems}" if problems else ""), flush=True)
        # Saved after every item: a slow model (phi4:14b, ~7 min/question
        # on 16GB) can outlive the caller's timeout, and partial results
        # are still a usable comparison.
        with open(os.path.join(out_dir, "holdout_results.json"), "w", encoding="utf-8") as f:
            json.dump({"label": label, "results": results}, f, indent=2, ensure_ascii=False)

    by_cat: dict[str, list] = {}
    for r in results:
        by_cat.setdefault(r["category"], []).append(r["result"])
    print(f"\n=== {label}: {sum(r['result']=='PASS' for r in results)}/{len(results)} PASS ===")
    for cat, rs in by_cat.items():
        print(f"  {cat:32} {rs.count('PASS')}/{len(rs)}")
    return results


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--label", required=True)
    p.add_argument("--holdout", default="eval/holdout.json")
    p.add_argument("--out-dir", default=None)
    p.add_argument("--ids", default=None, help="comma-separated item ids, run in this order")
    p.add_argument("--only-semantic-from", default=None,
                   help="previous holdout_results.json; run only items that took the semantic route there")
    args = p.parse_args()
    only = None
    if args.only_semantic_from:
        with open(args.only_semantic_from, encoding="utf-8") as f:
            prev = json.load(f)["results"]
        only = {r["id"] for r in prev if r["route"] == "semantic"}
    if args.ids:
        only = [i.strip() for i in args.ids.split(",")]
    out = args.out_dir or os.path.join("eval", "runs", f"holdout_{time.strftime('%Y-%m-%d')}_{args.label}")
    run(args.label, args.holdout, out, only)
